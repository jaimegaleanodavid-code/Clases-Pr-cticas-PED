def pedir_nombre_valido(mensaje):
    while True:
        nombre = input(mensaje).strip()
        if not nombre:
            print("Error El campo no puede estar vacio")
        elif not nombre.isalpha():
            print("Error: Ingrese solo un primer nombre (sin números, espacios ni símbolos).")
        else:
            return nombre.capitalize()

