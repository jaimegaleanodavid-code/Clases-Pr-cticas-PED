def pedir_numero_entero_positivo(mensaje):

    while True:
        entrada = input(mensaje)
        try:
            numero = int(entrada)
            if numero < 0:
                print("Error No se admiten numeros negativos, Intente de nuevo.")
            else:
                return numero
        except ValueError:
            print("Error Debe ingresar un numero entero valido, no letras ni decimales.")

def agregar_numero(pila):
    numero = pedir_numero_entero_positivo("Ingrese un numero entero positivo para agregar a la pila")
    pila.append(numero)
    print(f"El numero {numero} ha sido agregado correctamente.")

