def pedir_opcion():
    while True:
        try:
            return int(input("Seleccione una opcion (1-4): "))
        except ValueError:
            print("Error: Ingrese un numero entero valido.")

def validar_departamento():
    lista_validos = obtener_departamentos_validos()
    mapa_validos = {normalizar_texto(dep): dep for dep in lista_validos}

    while True:
        entrada = input("Ingrese el nombre del departamento de Nicaragua: ")
        entrada_norm = normalizar_texto(entrada)

        if entrada_norm in mapa_validos:
            return mapa_validos[entrada_norm]
        else:
            print("Error El departamento ingresado no pertenece a la lista oficial de Nicaragua")

def agregar_departamento(pila):
    dep = validar_departamento()
    pila.append(dep)
    print(f"Se agrego '{dep}' a la pila")

def remover_departamento(pila):
    if not pila:
        print("Error La pila esta vacia. No se puede remover ningun elemento")
